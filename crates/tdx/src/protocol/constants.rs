/// 请求帧头魔数
pub const MAGIC: u16 = 0x010C;
/// 请求头大小（不含 payload）
pub const REQUEST_HEADER_SIZE: usize = 12;
/// 响应头大小
pub const RESPONSE_HEADER_SIZE: usize = 16;

// 三步握手固定字节序列（与 pytdx 一致）
