#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    #[test]
    fn all_servers_deduplicated() {
        let set: HashSet<_> = ALL_SERVERS.iter().map(|s| (s.1, s.2)).collect();
        assert_eq!(set.len(), ALL_SERVERS.len());
    }

    #[test]
    fn primary_subset_of_all() {
        let set: HashSet<_> = ALL_SERVERS.iter().map(|s| (s.1, s.2)).collect();
        for s in PRIMARY_SERVERS {
            assert!(set.contains(&(s.ip, s.port)), "{} missing", s.ip);
        }
        assert_eq!(PRIMARY_SERVERS.len(), 10);
    }

    #[test]
    fn candidate_count_reasonable() {
        assert!(
            ALL_SERVERS.len() >= 100,
            "only {} servers",
            ALL_SERVERS.len()
        );
    }
}
